/**
 * Prepare the bundled narration, in Spanish and English, from the lesson text.
 * Run: node scripts/prepare-narration.mjs
 * Then: powershell.exe -NoProfile -File scripts/generate-narration.ps1 [-Languages en]
 * Audio is generated locally with installed Windows System.Speech voices.
 * Spanish files keep their original names; English files start with "en-".
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { createScenes } from '../dist/scenes.js';
import { LANGUAGES, translate } from '../dist/i18n.js';

const VOICES = {
  es: { culture: 'es-ES', voicePreference: ['Microsoft Helena Desktop', 'Microsoft Laura', 'Microsoft Helena'] },
  en: { culture: 'en-US', voicePreference: ['Microsoft Zira Desktop', 'Microsoft David Desktop'] },
};

// Respellings for the synthetic voice only. The written text, which is also the
// lookup key, stays unchanged. Zira reads "Teide" as "tide"; "Tay-day" is close
// to the Spanish pronunciation. Checked with System.Speech phoneme events.
const PRONUNCIATION = {
  es: [],
  en: [[/\bTeide\b/g, 'Tay-day']],
};

const assets = [];
const filenames = new Set();
const normalizedTexts = new Map(LANGUAGES.map(language => [language, new Map()]));

function normalizeText(value) {
  return typeof value === 'string'
    ? value.normalize('NFKC').replace(/\s+/gu, ' ').trim().replace(/\.+$/u, '').trim()
    : '';
}

function spokenText(language, text) {
  return PRONUNCIATION[language].reduce((spoken, [pattern, replacement]) => spoken.replace(pattern, replacement), text);
}

function addAsset(language, name, text) {
  if (!/^[a-z0-9][a-z0-9_-]*$/.test(name)) throw new Error(`Nombre de audio no válido: ${name}`);
  const key = normalizeText(text);
  if (!key) throw new Error(`El audio ${name} no tiene texto.`);
  // If lessons share an identical phrase in one language, bundle one recording.
  if (normalizedTexts.get(language).has(key)) return;
  const file = `${name}.wav`;
  if (filenames.has(file)) throw new Error(`Nombre de audio repetido: ${file}`);
  filenames.add(file);
  normalizedTexts.get(language).set(key, file);
  assets.push({ id: name, lang: language, file, text, spoken: spokenText(language, text) });
}

// Missions (dist/missions.js): the phrases of the answers and of the help.
const MISSION_PHRASES = [
  ['intro', 'mission.intro'], ['correct', 'mission.correct'], ['wrong', 'mission.wrong'],
  ['hint1', 'mission.hint1'], ['hint2', 'mission.hint2'], ['on-target', 'mission.onTarget'], ['done', 'mission.done'],
  ['dir-close', 'mission.dir.close'], ['dir-up', 'mission.dir.up'], ['dir-down', 'mission.dir.down'],
  ['dir-left', 'mission.dir.left'], ['dir-right', 'mission.dir.right'], ['dir-up-left', 'mission.dir.upLeft'],
  ['dir-up-right', 'mission.dir.upRight'], ['dir-down-left', 'mission.dir.downLeft'], ['dir-down-right', 'mission.dir.downRight'],
];

for (const language of LANGUAGES) {
  const prefix = language === 'es' ? '' : `${language}-`;
  const scenes = createScenes(language);
  addAsset(language, `${prefix}voice-test`, translate(language, 'voice.test'));
  for (const scene of scenes) {
    addAsset(language, `${prefix}${scene.id}-intro`, scene.description);
    for (const region of scene.regions) {
      addAsset(language, `${prefix}${scene.id}-${region.id}-label`, region.label);
      addAsset(language, `${prefix}${scene.id}-${region.id}-detail`, `${region.label}. ${region.description}`);
    }
  }
  for (const scene of scenes) {
    for (const mission of scene.missions ?? []) addAsset(language, `${prefix}${scene.id}-mission-${mission.id}`, mission.prompt);
  }
  for (const [name, key] of MISSION_PHRASES) addAsset(language, `${prefix}mission-${name}`, translate(language, key));
  // "You found 2 of 3": every possible count for the missions of one lesson.
  const total = Math.max(...scenes.map(scene => scene.missions?.length ?? 0));
  for (let count = 0; count <= total; count += 1) {
    addAsset(language, `${prefix}mission-found-${count}`, translate(language, 'mission.found', { count, total }));
  }
}

const content = {
  schema: 'tacto.narration.v2',
  provenance: {
    source: 'dist/scenes.js and dist/i18n.js',
    engine: 'Windows System.Speech.Synthesis.SpeechSynthesizer',
    voices: VOICES,
    format: 'WAV PCM 16-bit mono 22050 Hz',
    rate: 0,
    volume: 90,
    generation: 'Local; no external TTS service or downloaded audio.',
    regenerate: [
      'node scripts/prepare-narration.mjs',
      'powershell.exe -NoProfile -File scripts/generate-narration.ps1 [-Languages es,en]',
    ],
  },
  assets,
};

const tables = LANGUAGES.map(language => [
  language,
  assets.filter(asset => asset.lang === language).map(asset => [normalizeText(asset.text), `./audio/${asset.file}`]),
]);
const paths = assets.map(asset => `./audio/${asset.file}`);
const moduleSource = `/**
 * Generated by scripts/prepare-narration.mjs from the built-in lesson text.
 * WAV files: local Windows System.Speech. Spanish (es-ES, Helena Desktop) and
 * English (en-US, Zira Desktop). Regenerate with the scripts recorded in
 * scripts/narration-content.json.
 * This lookup contains only bundled phrases; user-created text has no fallback.
 */
import { getLanguage } from './i18n.js';

export const NARRATION_ASSETS = Object.freeze(${JSON.stringify(paths, null, 2)});

const recordings = new Map(${JSON.stringify(tables, null, 2)}.map(([language, entries]) => [language, new Map(entries)]));

function normalizeText(value) {
  return typeof value === 'string'
    ? value.normalize('NFKC').replace(/\\s+/gu, ' ').trim().replace(/\\.+$/u, '').trim()
    : '';
}

/** Return a local recording URL for an exact normalized phrase in a language, otherwise null. */
export function getNarrationUrl(text, language = getLanguage()) {
  const path = recordings.get(language)?.get(normalizeText(text));
  return path ? new URL(path, import.meta.url).href : null;
}
`;

await mkdir(new URL('../dist/audio/', import.meta.url), { recursive: true });
await writeFile(new URL('./narration-content.json', import.meta.url), JSON.stringify(content, null, 2) + '\n', 'utf8');
await writeFile(new URL('../dist/narration.js', import.meta.url), moduleSource, 'utf8');
const counts = LANGUAGES.map(language => `${language}: ${assets.filter(asset => asset.lang === language).length}`).join(', ');
console.log(`Preparadas ${assets.length} narraciones locales (${counts}). Ejecuta scripts/generate-narration.ps1 para crear los WAV.`);
